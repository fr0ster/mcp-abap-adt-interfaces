/**
 * The names the repository quick search takes as its type filter, one table
 * per release variant — `ISearchObjectsParams.objectType`.
 *
 * **The release's own list, not the type tables.** The filter is read against
 * the object types list of `GET /sap/bc/adt/repository/informationsystem/
 * objecttypes?maxItemCount=999&name=*&data=usedByProvider`: each item a name
 * and `type:<code>;usedBy:…`, every item used by `quick_search`. A name
 * selects what its item says (measured 2026-10-29, read only, identical on
 * S/4HANA 2025 on-premise and ABAP cloud, `maxResults=200`):
 * - most names are a main type, their `type` the main code (`DEVC` →
 *   `DEVC/K`, `CLAS` → `CLAS/OC`, `AUTH` → `AUTH`); `TABL` selects both
 *   `TABL/DT` and `TABL/DS`;
 * - some are aliases of one code: `STRU` selects only `TABL/DS`, `DTAB` only
 *   `TABL/DT` (`REPO`, `INCL`, `FUNC`, `BADI` likewise);
 * - about fifty are groups (`type:WGRP`), which select their members:
 *   `ABAP_TEST_COCKPIT` answers `CHKO`, `CHKV`, `CHKC` and `CHKE` hits;
 * - an unknown name is refused `400`.
 *
 * **A code is not a filter value.** A code equal to an item's `type` selects as
 * that item; any other code selects as the text before its `/` — `ENHO/XHH`
 * and `ENHO/XX` answer as `ENHO` — and a capped search for it answers other
 * first hits than its main type does; an unknown code (`NOPE/XX`) answers
 * nothing, silently. The types cannot see which, so the filter takes a name.
 * A subtype is searched by its alias (`STRU`); one without an alias
 * (`ENHO/XHH`) cannot be searched alone, and the caller filters the hits.
 *
 * Constants and types only. The two newer tables are written from the
 * recorded lists, item by item; 7.40 has no list, and its table holds the
 * names measured to select there.
 */

import type { AdtVariant } from './AdtTypeTables';

/**
 * The corpus case behind a search name: the release's recorded object types
 * list (`R` its case prefix), or, on 7.40, which has none, its recorded quick
 * searches.
 */
export type AdtSearchTypeEvidence<R extends string> =
  | `search-types-${R}--objecttypes`
  | 'search-types-basis-740--quick-search';

/**
 * What one item of a recorded list says about a name: the code it selects
 * (`type`, as the answer writes it — `'TABL/DS'` for `STRU`, a code the type
 * tables may not hold), or that it is a group (`type:WGRP`), or both, where
 * the list holds the name twice (`HOTA`: `HOTA/HDI` and a group).
 */
export type AdtListedSearchType<R extends string> = (
  | { readonly type: string; readonly group?: true }
  | { readonly type?: never; readonly group: true }
) & {
  /** The release's recorded list. */
  readonly evidence: `search-types-${R}--objecttypes`;
};

/** A name measured to select on a release with no list (7.40). */
export interface IAdtMeasuredSearchType {
  readonly type?: never;
  readonly group?: never;
  /**
   * The codes of the hits its recorded quick search answered (`query=*`,
   * `maxResults=200`), as the answer writes them: what the name selects
   * there, read from the hits since the release has no list to say it.
   */
  readonly answered: readonly [string, ...string[]];
  /** The release's recorded quick searches. */
  readonly evidence: 'search-types-basis-740--quick-search';
}

/** What a search type table `satisfies`: an entry per name. */
export type AdtSearchTypeTable<
  F extends AdtListedSearchType<string> | IAdtMeasuredSearchType,
> = { readonly [name: string]: F };

